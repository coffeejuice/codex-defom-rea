# Generates apps/moproj2mst/src/model/units_table.inc from a COPY of DEF_GUI_MO_64.exe and the
# Ghidra decompile of the unit-table constructor 0x1402eaaf0 (calls of 0x1402ea840).
# usage: python -I gen_units.py <exe copy> <decompile of 1402eaaf0> <out .inc>
# Reads only. Pointers in .data are taken at the preferred image base 0x140000000.
import re, struct, sys

exe, dec, outp = sys.argv[1:4]
d = open(exe, 'rb').read()
B = 0x140000000
pe = struct.unpack_from('<I', d, 0x3c)[0]
opt = pe + 24
nsec = struct.unpack_from('<H', d, pe + 6)[0]
sh = opt + struct.unpack_from('<H', d, pe + 20)[0]
secs = []
for i in range(nsec):
    o = sh + 40 * i
    vs, va, rs, ra = struct.unpack_from('<IIII', d, o + 8)
    secs.append((va, vs, ra, rs))

def off(va):
    r = va - B
    for sva, svs, sra, srs in secs:
        if sva <= r < sva + srs:
            return sra + r - sva
    return None          # .bss: zero at start (nothing else writes these ranges)

def q(va):  o = off(va); return 0 if o is None else struct.unpack_from('<Q', d, o)[0]
def dbl(va): o = off(va); return 0.0 if o is None else struct.unpack_from('<d', d, o)[0]
def byte(va): o = off(va); return 0 if o is None else d[o]
def cstr(va):
    if va == 0:
        return None      # QString(const char* 0) = null
    o = off(va); e = d.index(b'\0', o); return d[o:e]

src = re.sub(r'\s+', '', open(dec).read())
strs = re.findall(r'QString__QEAA_PEBD_Z\(\w+,&UNK_([0-9a-f]+)\)', src)
calls = re.findall(r'FUN_1402ea840\(\*param_1,(\w+),\w+,\w+,(\d+),(\w+),(\w+),(\w+),(\w+),(\w+)\)', src)
assert len(calls) == 43 and len(strs) == 86, (len(calls), len(strs))

def cs(b):
    if b is None:
        return 'nullptr'
    return '"' + ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92) else '\\x%02x""' % c for c in b) + '"'

def hx(v): return float.hex(v) if v == v else 'NAN'

L = ['// Generated by docs/re/moproj2mst/p17/tools/gen_units.py from DEF_GUI_MO_64.exe (copy).',
     '// Unit table 0x143d76368 built by 0x1402eaaf0: one 0x1402ea840 call per category.',
     '// Do not edit by hand.', '']
names_si = []
for k in range(0x30):
    names_si.append((cstr(0x1427bc000 + k * 0x28), cstr(0x1427bc014 + k * 0x28)))
L.append('// 0x140917de0: unit name of a kind, SI (+0) and English (+0x14), stride 0x28 at 0x1427bc000')
L.append('static const char* const kUnitNameSI[] = {')
L += ['    %s,  // 0x%x' % (cs(a), k) for k, (a, b) in enumerate(names_si[:0x2c])]
L.append('};')
L.append('static const char* const kUnitNameEN[] = {')
L += ['    %s,  // 0x%x' % (cs(b), k) for k, (a, b) in enumerate(names_si[:0x2c])]
L.append('};')
L.append('')
for idx, c in enumerate(calls):
    k = int(c[0], 0); n = int(c[1]); p6, p7, p8, p9, p10 = [int(x, 0) for x in c[2:7]]
    a = cstr(int(strs[2 * idx], 16)); b = cstr(int(strs[2 * idx + 1], 16))
    units = [cstr(q(p6 + 8 * i)) for i in range(n)]
    L.append('// kind 0x%x: %s / %s (n=%d, p6=%#x p8=%#x p9=%#x p10=%#x)' % (k, a.decode(), b.decode(), n, p6, p8, p9, p10))
    L.append('static const char* const kU%02x[] = {%s};' % (k, ', '.join(cs(u) for u in units)))
    conv = []
    for i in range(n):          # from
        for j in range(n):      # to
            e = j * n + i
            f = dbl(p8 + 8 * e) if p8 else 1.0      # 0x1402ee5e0 default factor (0x1421249e0 = 1.0)
            o = dbl(p9 + 8 * e) if p9 else 0.0
            fl = byte(p10 + e) if p10 else 0
            conv.append('{%s, %s, %d}' % (hx(f), hx(o), fl))
    L.append('static const Conv kC%02x[] = {%s};' % (k, ', '.join(conv)))
L.append('')
L.append('static const Category kCategories[] = {')
for idx, c in enumerate(calls):
    k = int(c[0], 0); n = int(c[1])
    a = cstr(int(strs[2 * idx], 16)); b = cstr(int(strs[2 * idx + 1], 16))
    L.append('    {0x%x, %s, %s, %d, kU%02x, kC%02x},' % (k, cs(a), cs(b), n, k, k))
L.append('};')
open(outp, 'w', newline='\n').write('\n'.join(L) + '\n')
print('wrote', outp, len(calls), 'categories')
