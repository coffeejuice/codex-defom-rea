# Golden segment tables for the p8-04 tier-1 test (port/defcmd/tests/test_p8_04_dxf.cpp), and the
# model-vs-oracle check of the DXF cases.
#
#   python -I tests/commands/GFREAD/models/dxf_golden.py golden   > tests/commands/GFREAD/data/dxf_segments.golden
#   python -I tests/commands/GFREAD/models/dxf_golden.py oracle   (needs the oracle cache)
#
# "golden": for every GFREAD DXF case (gfread_2d_dxf.json, gfread_dxf_*.json) and every DXF file
# its CMD.KEY reads (in order, the tolerance G carried from one read to the next like the
# original process), the output of FUN_140422ab0 according to dxf_model.py: return code, point and
# segment counts, the segment table (6 doubles per segment, hex bits) and G after the read.
#
# "oracle": the model's whole DXF path (segments, dedupe, Fortran chaining stage, KEY lines) for
# each case compared with the DIEGEO record of object 1 in the cached oracle OUT.KEY.
import glob, json, math, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dxf_model as M  # noqa: E402

GF = os.path.dirname(HERE)
DATA = os.path.join(GF, 'data')


def hx(v):
    return struct.pack('<d', v).hex()


def cases():
    out = []
    files = [os.path.join(GF, 'gfread_2d_dxf.json')] + sorted(glob.glob(os.path.join(GF, 'gfread_dxf_*.json')))
    for fn in files:
        d = json.load(open(fn))
        name = os.path.splitext(os.path.basename(fn))[0]
        inputs = {i['name']: i for i in d['inputs']}
        cmd = inputs['CMD.KEY']['text'].split('\n')
        seq = []
        for k, l in enumerate(cmd):
            if l.startswith('GFREAD'):
                src = inputs[cmd[k + 1]]['source']
                base = os.path.basename(src)
                if os.path.exists(os.path.join(DATA, base)):
                    seq.append(('data', base))
                else:
                    seq.append(('install', base))
        out.append((name, d['label'], seq))
    return out


def path_of(kind, base):
    if kind == 'data':
        return os.path.join(DATA, base)
    return os.path.join(r'C:\Program Files\SFTC\DEFORM\v11.0.2\Tutorials', base)


def read_segments(path, G):
    """FUN_140422ab0 per the model: (rc, npts, nseg, segs, G after)"""
    data = open(path, 'rb').read()
    P = M.Parser(data, G)
    r = P.run()
    if r != 0:
        return r, 0, 0, [], 0.0
    rc, nseg, npts, segs = M.segments(P)
    if rc != 0:
        return rc, 0, 0, [], 0.0
    size = M.size_of(segs)
    return 0, npts, nseg, segs, size * 0.01


def golden():
    print('# generated by tests/commands/GFREAD/models/dxf_golden.py golden (dxf_model.py); do not edit')
    for name, label, seq in cases():
        G = 1e-9
        for kind, base in seq:
            p = path_of(kind, base)
            if not os.path.exists(p):
                print('# %s: %s missing, skipped' % (name, p))
                break
            g0 = G
            rc, npts, nseg, segs, G = read_segments(p, G)
            print('read %s %s %s g0 %s rc %d npts %d nseg %d g %s' % (name, kind, base, hx(g0), rc, npts, nseg, hx(G)))
            for s in segs:
                print('  ' + ' '.join(hx(v) for v in s))


def diegeo(text, obj):
    ls = text.replace('\r', '').split('\n')
    for i, l in enumerate(ls):
        t = l.split()
        if len(t) >= 4 and t[0] == 'DIEGEO' and int(t[1]) == obj:
            n = int(t[3])
            return [l] + ls[i + 1:i + 1 + n]
    return None


def oracle():
    cache = os.environ.get('DEFORM_ORACLE_CACHE') or os.path.join(os.environ['USERPROFILE'], '.deform-oracle')
    ents = {}
    for rj in glob.glob(os.path.join(cache, 'entries', '*', '*', 'result.json')):
        j = json.load(open(rj))
        if j['label'] not in ents or j.get('created', '') > ents[j['label']][0].get('created', ''):
            ents[j['label']] = (j, os.path.dirname(rj))
    seed = None
    ok = bad = 0
    for name, label, seq in cases():
        if label not in ents:
            print('%-40s no oracle entry' % name)
            continue
        j, d = ents[label]
        orig = diegeo(open(os.path.join(d, 'files', 'OUT.KEY'), 'rb').read().decode('latin1'), 1)
        G = 1e-9
        pred = None
        for kind, base in seq:
            r = M.run(path_of(kind, base), G)
            if r.get('result') == 0:
                pred = M.key_lines(r)
            G = r.get('tol', 0.0) if 'tol' in r else (0.0 if r.get('result') in (-500, -10000) else G)
        if pred is None:
            # reader failed: object 1 keeps the IN.KEY curve (DIEGEO 1 1 2)
            verdict = orig is not None and orig[0].split()[2] == '1'
        elif orig is None:
            # KFWRIT leaves out a degenerate one-segment curve (gfread_dxf_seq_tolzero)
            verdict = len(pred) == 2
        else:
            verdict = orig == pred
        print('%-40s %s' % (name, 'same' if verdict else 'DIFFERENT'))
        if not verdict:
            bad += 1
            print('   orig:', orig[:3] if orig else orig)
            print('   pred:', pred[:3] if isinstance(pred, list) else pred)
        else:
            ok += 1
    print('%d same, %d different' % (ok, bad))


if __name__ == '__main__':
    {'golden': golden, 'oracle': oracle}[sys.argv[1]]()
