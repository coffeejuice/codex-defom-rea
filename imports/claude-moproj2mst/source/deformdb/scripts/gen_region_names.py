"""Generate src/region_names.cpp from docs/re/address_region_names.json."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
d = json.loads((root / "docs/re/address_region_names.json").read_text())
out = ["// Generated by scripts/gen_region_names.py from docs/re/address_region_names.json. Do not edit.",
       '#include "deformdb/database.hpp"', "", "namespace deformdb {", "namespace {"]
# DEFORM's own 3D v>10000 A name table lists LLRFL before LLSIZ, but the loader uses
# region 48 for the element size field and 49 for the face radiation flux (spec section 6.4).
