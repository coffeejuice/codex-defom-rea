"""Generate the keyword registry from DEF_PRE_64.exe's own table.

Reads the 304 records of 0x30 bytes at 0x140544400 (.rdata) straight from the PE file and writes

  defmodel/include/defmodel/keyword_registry_table.hpp   constexpr table, in the binary's order
  docs/re/keyword_registry.tsv                           the same data sorted by id

Record layout (FUN_1402f78d0 / FUN_1402f7950 / FUN_1402f77e0 / FUN_1402f7830 / FUN_1402f7880 /
FUN_1402f79c0 / FUN_1402f7a70):

  +0x00 int32 id, +0x04 pad, +0x08 char* name, +0x10 int32 group, +0x14 int32 flag,
  +0x18 handler1, +0x20 handler2 (KEY write), +0x28 handler3 (axis label)

Usage: gen_keyword_registry.py [--exe PATH] [--check]
  --check   do not write; exit 1 if the committed files differ from what the binary gives
            (77 = skipped, the binary is not installed).
The binary is only read. Default path: $DEFORM_PRE_EXE or the v11.0.2 install.
"""
import argparse, os, pathlib, struct, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HEADER = ROOT / "port/defmodel/include/defmodel/keyword_registry_table.hpp"
TSV = ROOT / "docs/re/keyword_registry.tsv"
DEFAULT_EXE = os.environ.get("DEFORM_PRE_EXE", r"C:\Program Files\SFTC\DEFORM\v11.0.2\DEF_PRE_64.exe")

TABLE_VA = 0x140544400
RECORD_SIZE = 0x30
RECORD_COUNT = 0x130          # loop bound "0x12f < i" in FUN_1402f78d0 and FUN_1402f7950
TRAILER = b"ERROR: KEYWORD NOT EXISTS!\0"   # FUN_1402f7720's string sits right after the table

# Group codes as FUN_1401b6520 dispatches them (case = group - 1).
GROUPS = {1: ("simulation control", "SimulationControl", 0x14039AA90),
          2: ("object", "Object", 0x14038B8A0),
          3: ("inter-object", "InterObject", 0x140388FB0),
          4: ("material", "Material", 0x140384A50),
          5: ("phase transformation", "PhaseTransformation", 0x140383120),
          6: ("command", "Command", 0x140378E00),
          7: ("dimension", "Dimension", 0x14037E530)}


class Pe:
    def __init__(self, path):
        self.d = pathlib.Path(path).read_bytes()
        d = self.d
        pe = struct.unpack_from("<I", d, 0x3C)[0]
        if d[pe:pe + 4] != b"PE\0\0":
            sys.exit("not a PE file: %s" % path)
        nsec, = struct.unpack_from("<H", d, pe + 6)
        optsize, = struct.unpack_from("<H", d, pe + 20)
        self.base, = struct.unpack_from("<Q", d, pe + 24 + 24)
        self.secs = []
        o = pe + 24 + optsize
        for i in range(nsec):
            name, vsize, va, rsize, raw = struct.unpack_from("<8sIIII", d, o + 40 * i)
            self.secs.append((name.rstrip(b"\0").decode(), va, vsize, raw, rsize))

    def off(self, va):
        rva = va - self.base
        for _, sva, vsize, raw, rsize in self.secs:
            if sva <= rva < sva + vsize and rva - sva < rsize:
                return raw + rva - sva
        raise ValueError("address 0x%x not in file data" % va)

    def section(self, va):
        rva = va - self.base
        return next(n for n, sva, vs, _, _ in self.secs if sva <= rva < sva + vs)

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)].decode("ascii")


def read_table(exe):
    pe = Pe(exe)
    if pe.section(TABLE_VA) != ".rdata":
        sys.exit("registry is not in .rdata; wrong binary?")
    end = pe.off(TABLE_VA + RECORD_COUNT * RECORD_SIZE)
    if pe.d[end:end + len(TRAILER)] != TRAILER:
        sys.exit("table end marker not found; wrong binary?")
    rows = []
    for i in range(RECORD_COUNT):
        o = pe.off(TABLE_VA + i * RECORD_SIZE)
        rid, pad, name_p, group, flag, h1, h2, h3 = struct.unpack_from("<iIQiiQQQ", pe.d, o)
        if pad != 0 or group not in GROUPS:
            sys.exit("unexpected record %d" % i)
        rows.append(dict(index=i, id=rid, name=pe.cstr(name_p), group=group, flag=flag,
                         h1=h1, h2=h2, h3=h3))
    if sorted(r["id"] for r in rows) != list(range(RECORD_COUNT)):
        sys.exit("ids are not a permutation of 0..303")
    return rows


def render_header(rows, exe_name):
    out = ["// Generated by port/defmodel/scripts/gen_keyword_registry.py from %s. Do not edit." % exe_name,
           "// Source: the keyword registry at 0x140544400 (.rdata), 304 records of 0x30 bytes, in the",
           "// binary's own order (lookups scan in this order; it is not sorted by id).",
           "#pragma once",
           "",
           '#include "defmodel/keyword_registry_types.hpp"',
           "",
           "namespace def::model {",
           "",
           "inline constexpr KeywordRecord kKeywordTable[kKeywordCount] = {"]
    for r in rows:
        out.append('    {%3d, "%s", KeywordGroup::%s, %d, 0x%X, 0x%X, 0x%X},' % (
            r["id"], r["name"], GROUPS[r["group"]][1], r["flag"], r["h1"], r["h2"], r["h3"]))
    out += ["};", "", "}  // namespace def::model", ""]
    return "\n".join(out)


def render_tsv(rows):
    out = ["id\tname\tgroup_code\tgroup\tflag\thandler1\thandler2\thandler3\ttable_index"]
    for r in sorted(rows, key=lambda r: r["id"]):
        out.append("%d\t%s\t%d\t%s\t%d\t0x%x\t0x%x\t0x%x\t%d" % (
            r["id"], r["name"], r["group"], GROUPS[r["group"]][0], r["flag"],
            r["h1"], r["h2"], r["h3"], r["index"]))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=DEFAULT_EXE)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check and not os.path.exists(a.exe):
        print("skipped: %s not found" % a.exe)
        return 77
    rows = read_table(a.exe)
    files = {HEADER: render_header(rows, pathlib.Path(a.exe).name), TSV: render_tsv(rows)}
    if a.check:
        bad = [p for p, text in files.items()
               if not p.exists() or p.read_text(encoding="ascii").replace("\r\n", "\n") != text]
        for p in bad:
            print("out of date: %s" % p.relative_to(ROOT))
        print("registry: %d records, %s" % (len(rows), "MISMATCH" if bad else "matches the binary"))
        return 1 if bad else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("ascii"))
        print("wrote %s" % p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
