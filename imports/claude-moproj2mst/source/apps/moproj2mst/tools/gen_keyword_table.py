"""Generate the keyword table of DEF_GUI_MO_64.exe (the copy of DEF_PRE's KEY keyword registry).

Reads the 0x130 records of 0x30 bytes at 0x1427c06e0 (loop bound "0x12f < i" in FUN_140922160)
straight from the PE file (read only) and writes src/mst/keyword_table.inc: one {id, name} per
record, in the binary's order. Record layout: +0x00 int32 id, +0x08 char* name (DEF_PRE's
port/defmodel/scripts/gen_keyword_registry.py has the full layout).

Usage: python -I gen_keyword_table.py [--exe PATH] [--check]
  --check  do not write; exit 1 if the committed file differs from what the binary gives.
Default exe: the analysis copy deform-rea-work/gui_mo/DEF_GUI_MO_64.exe.
"""
import argparse, pathlib, struct, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src/mst/keyword_table.inc"
DEFAULT_EXE = r"C:\Users\alext\Projects\deform-rea-work\gui_mo\DEF_GUI_MO_64.exe"
TABLE_VA = 0x1427C06E0
RECORD_SIZE = 0x30
RECORD_COUNT = 0x130
MISSING_VA = 0x1427C3FE0   # "ERROR: KEYWORD NOT EXISTS!" (FUN_140921f30)


class Pe:
    def __init__(self, path):
        d = self.d = pathlib.Path(path).read_bytes()
        pe = struct.unpack_from("<I", d, 0x3C)[0]
        if d[pe:pe + 4] != b"PE\0\0":
            sys.exit("not a PE file: %s" % path)
        nsec, = struct.unpack_from("<H", d, pe + 6)
        optsize, = struct.unpack_from("<H", d, pe + 20)
        self.base, = struct.unpack_from("<Q", d, pe + 24 + 24)
        self.secs = []
        s = pe + 24 + optsize
        for i in range(nsec):
            va, vsize, raw, rsize = (struct.unpack_from("<I", d, s + 40 * i + 12)[0],
                                     struct.unpack_from("<I", d, s + 40 * i + 8)[0],
                                     struct.unpack_from("<I", d, s + 40 * i + 20)[0],
                                     struct.unpack_from("<I", d, s + 40 * i + 16)[0])
            self.secs.append((va, max(vsize, rsize), raw, rsize))

    def off(self, va):
        rva = va - self.base
        for v, size, raw, rsize in self.secs:
            if v <= rva < v + size:
                if rva - v >= rsize:
                    sys.exit("VA %#x is in uninitialised data" % va)
                return raw + rva - v
        sys.exit("VA %#x not mapped" % va)

    def cstr(self, va):
        o = self.off(va)
        return self.d[o:self.d.index(b"\0", o)]


def render(exe):
    pe = Pe(exe)
    lines = ["// Generated by tools/gen_keyword_table.py from DEF_GUI_MO_64.exe; do not edit.",
             "// @data 0x1427c06e0  keyword table, %d records x 0x30: {id (+0x00), name (+0x08)}" % RECORD_COUNT]
    for i in range(RECORD_COUNT):
        o = pe.off(TABLE_VA + i * RECORD_SIZE)
        kid, = struct.unpack_from("<i", pe.d, o)
        nva, = struct.unpack_from("<Q", pe.d, o + 8)
        name = pe.cstr(nva).decode("ascii")
        if any(c in name for c in ('"', "\\")) or not name.isprintable():
            sys.exit("unexpected name bytes at record %d" % i)
        lines.append('{%d, "%s"},' % (kid, name))
    missing = pe.cstr(MISSING_VA).decode("ascii")
    if missing != "ERROR: KEYWORD NOT EXISTS!":
        sys.exit("unexpected missing-keyword text: %r" % missing)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=DEFAULT_EXE)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not pathlib.Path(a.exe).is_file():
        print("skipped: no exe copy at", a.exe)
        sys.exit(77)
    text = render(a.exe)
    if a.check:
        old = OUT.read_bytes().replace(b"\r\n", b"\n").decode("ascii") if OUT.exists() else ""
        sys.exit(0 if old == text else 1)
    OUT.write_text(text, encoding="ascii", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
